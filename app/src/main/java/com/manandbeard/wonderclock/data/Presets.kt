    fun default(): Preset = all.first { it.id == "midnight" }

    fun byId(id: String): Preset? = all.firstOrNull { it.id == id }

    /** The preset a freshly dropped widget of each kind starts from. */
    fun forStyle(style: ClockStyle): Preset = when (style) {
        ClockStyle.ANALOG -> byId("classic")
        ClockStyle.WORDS -> byId("wordy")
        ClockStyle.WORD_GRID -> byId("matrix")
        ClockStyle.BINARY -> byId("binary")
        ClockStyle.STACKED -> byId("sunset")
        ClockStyle.DIGITAL -> byId("midnight")
    } ?: default()
}
